    public const int TYPE_CONSTANTS = 1;

    public const int TYPE_FUNCTION = 2;

    public const int TYPE_INTERFACE = 4;

    public const int TYPE_TRAIT = 8;

    public const int TYPE_CLASS = 16;

    public const int TYPE_ENUM = 32;

    public const int TYPE_CLASSISH = self::TYPE_INTERFACE | self::TYPE_TRAIT | self::TYPE_CLASS | self::TYPE_ENUM;

    private function __construct() {}

    public static function bootstrap(): void
    {
        self::loadConstants();
        self::autoload(static function (): void {
            self::loadFunctions();
        });
    }

    public static function preload(): void
    {
        self::loadConstants();
        self::autoload(static function (): void {
            self::loadFunctions();
            self::loadInterfaces();
            self::loadTraits();
            self::loadClasses();
            self::loadEnums();
        });
    }

    private static function load(string $file): void
    {
        require_once dirname(__DIR__, 2) . '/' . $file;
    }

    private static function autoload(Closure $callback): void
    {
        $loader = static function (string $classname): null|bool {
            $file = self::lookupClassish($classname);
            if (!$file) {
                return null;
            }

            self::load($file);

            return true;
        };

        spl_autoload_register($loader);
        $callback();
        spl_autoload_unregister($loader);
    }

    private static function loadConstants(): void
    {
        foreach (self::CONSTANTS as $constant => $file) {
            if (defined($constant)) {
                continue;
            }

            self::load($file);
        }
    }

    private static function loadFunctions(): void
    {
        foreach (self::FUNCTIONS as $function => $file) {
            if (function_exists($function)) {
                continue;
            }

            self::load($file);
        }
    }

    private static function loadInterfaces(): void
    {
        foreach (self::INTERFACES as $interface => $file) {
            if (interface_exists($interface)) {
                continue;
            }

            self::load($file);
        }
    }

    private static function loadTraits(): void
    {
        foreach (self::TRAITS as $trait => $file) {
            if (trait_exists($trait)) {
                continue;
            }

            self::load($file);
        }
    }

    private static function loadClasses(): void
    {
        foreach (self::CLASSES as $class => $file) {
            if (class_exists($class)) {
                continue;
            }

            self::load($file);
        }
    }

    private static function loadEnums(): void
    {
        foreach (self::ENUMS as $enum => $file) {
            if (enum_exists($enum)) {
                continue;
            }

            self::load($file);
        }
    }

    private static function lookupClassish(string $classname): null|string
    {
        /**
         * @var array<non-empty-string, non-empty-string>|null $lookup
         */
        static $lookup = null;

        if (null === $lookup) {
            $lookup = array_merge(self::TRAITS, self::INTERFACES, self::CLASSES, self::ENUMS);
        }

        return $lookup[$classname] ?? null;
    }
